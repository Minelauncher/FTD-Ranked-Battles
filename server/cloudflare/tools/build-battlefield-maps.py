"""Build shaded overview maps from the development-only FTD MapExport samples.

Usage: python tools/build-battlefield-maps.py [path/to/tests/map-data]
Standard library only. Re-run tests/Export-Maps.ps1 after changing FTD versions.
Images describe native campaign-map terrain, not exact collision heights.
"""
import array
import base64
import hashlib
import json
from pathlib import Path
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent.parent / "tests/map-data"
STOPS = [(-500, (12, 36, 59)), (-150, (20, 67, 91)), (-20, (36, 112, 132)),
         (0, (64, 145, 155)), (1, (179, 171, 117)), (25, (99, 132, 85)),
         (180, (82, 110, 73)), (350, (153, 144, 119)), (500, (225, 224, 208))]


def colour(height):
    for (lo, a), (hi, b) in zip(STOPS, STOPS[1:]):
        if height <= hi:
            t = max(0, min(1, (height - lo) / (hi - lo)))
            return [a[i] + t * (b[i] - a[i]) for i in range(3)]
    return STOPS[-1][1]


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


levels = [-500 + i * 500 / 15 for i in range(16)] + [1 + i * 499 / 31 for i in range(32)]
shades = [.7, .85, 1, 1.15, 1.3]
palette = bytes(round(max(0, min(255, c * shade))) for level in levels for shade in shades for c in colour(level))
maps = {}
for world in ("neter", "aote"):
    metadata = json.loads((DATA / (world + ".json")).read_text(encoding="utf-8-sig"))
    raw = (DATA / (world + ".heights")).read_bytes()
    heights = array.array("f", raw)
    if sys.byteorder != "little":
        heights.byteswap()
    w, h = metadata["width"], metadata["height"]
    assert len(heights) == w * h and metadata["rowOrder"] == "south-to-north"
    rows = bytearray()
    for y in range(h - 1, -1, -1):  # Browser's top row is north, native data starts south.
        rows.append(0)
        for x in range(w):
            value = heights[y * w + x]
            west = heights[y * w + max(0, x - 1)]
            north = heights[min(h - 1, y + 1) * w + x]
            shade = max(0, min(4, round(2 + (north + west - 2 * value) / 25.5)))
            level = max(0, min(15, round((value + 500) / 500 * 15))) if value <= 0 else 16 + max(0, min(31, round((value - 1) / 499 * 31)))
            rows.append(level * 5 + shade)
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 3, 0, 0, 0))
           + chunk(b"PLTE", palette) + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))
    (DATA / (world + ".png")).write_bytes(png)
    metadata.update(heightSha256=hashlib.sha256(raw).hexdigest(), imageSha256=hashlib.sha256(png).hexdigest())
    maps[world] = dict(metadata, image="data:image/png;base64," + base64.b64encode(png).decode("ascii"))
    print(f"{world}: {w}x{h}, {len(png):,} PNG bytes")

output = ROOT / "src/battlefield-maps.js"
output.write_text("// Generated by tools/build-battlefield-maps.py from native FTD 4.3.4.1 map terrain.\n"
                  "// North up; west left; no campaign icons, fog, or image margins.\n"
                  "export const battlefieldMaps = " + json.dumps(maps, ensure_ascii=True, separators=(",", ":")) + ";\n", encoding="utf-8")
